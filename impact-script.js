let currentLang = 'en';

function updateImpactPage(lang) {
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (impactTranslations[lang] && impactTranslations[lang][key]) {
            // For buttons and simple elements, just replace textContent
            if (el.children.length === 0 || el.tagName === 'BUTTON' || el.tagName === 'INPUT') {
                el.textContent = impactTranslations[lang][key];
            } else {
                // For elements with possible inline icons (like the revolution text)
                const textNode = Array.from(el.childNodes).find(n => n.nodeType === 3);
                if (textNode) textNode.textContent = impactTranslations[lang][key];
                else if (el.tagName === 'LI' || el.tagName === 'DIV') el.innerHTML = impactTranslations[lang][key];
            }
        }
    });

    // Update language toggle button texts (desktop and mobile)
    const desktopToggleText = document.getElementById('langToggleText');
    const mobileToggleText = document.getElementById('mobileLangText');
    if (desktopToggleText) desktopToggleText.innerText = lang === 'en' ? 'हिंदी' : 'English';
    if (mobileToggleText) mobileToggleText.innerText = lang === 'en' ? 'हिंदी' : 'English';

    // Update newsletter placeholder
    const footerNewsEmail = document.getElementById('footerNewsEmail');
    if (footerNewsEmail) footerNewsEmail.placeholder = lang === 'en' ? 'Enter your email' : 'अपना ईमेल दर्ज करें';
    
    // Also update any input placeholders that are not data-i18n (none in impact page except newsletter)
}

function toggleLang() {
    currentLang = currentLang === 'en' ? 'hi' : 'en';
    updateImpactPage(currentLang);
    localStorage.setItem('vigrid_lang_impact', currentLang);
}

document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('vigrid_lang_impact');
    if (savedLang && (savedLang === 'en' || savedLang === 'hi')) {
        currentLang = savedLang;
    }
    updateImpactPage(currentLang);

    // Language toggle buttons
    const desktopLangBtn = document.getElementById('langToggleBtn');
    const mobileLangBtn = document.getElementById('mobileLangSwitch');
    if (desktopLangBtn) desktopLangBtn.addEventListener('click', toggleLang);
    if (mobileLangBtn) mobileLangBtn.addEventListener('click', toggleLang);

    // Mobile menu toggle
    const menuToggle = document.getElementById('menuToggle');
    const navLinks = document.getElementById('navLinks');
    if (menuToggle && navLinks) {
        menuToggle.addEventListener('click', (e) => {
            e.stopPropagation();
            navLinks.classList.toggle('active');
            const icon = menuToggle.querySelector('i');
            if (icon) {
                if (navLinks.classList.contains('active')) {
                    icon.classList.remove('fa-bars');
                    icon.classList.add('fa-times');
                } else {
                    icon.classList.remove('fa-times');
                    icon.classList.add('fa-bars');
                }
            }
        });
        document.addEventListener('click', (event) => {
            if (navLinks.classList.contains('active') && !navLinks.contains(event.target) && !menuToggle.contains(event.target)) {
                navLinks.classList.remove('active');
                const icon = menuToggle.querySelector('i');
                if (icon) {
                    icon.classList.remove('fa-times');
                    icon.classList.add('fa-bars');
                }
            }
        });
        navLinks.querySelectorAll('a, .mobile-lang-switch').forEach(link => {
            link.addEventListener('click', () => {
                navLinks.classList.remove('active');
                const icon = menuToggle.querySelector('i');
                if (icon) {
                    icon.classList.remove('fa-times');
                    icon.classList.add('fa-bars');
                }
            });
        });
    }

    // Buttons alerts
    const seeJourneyBtn = document.getElementById('seeJourneyBtn');
    if (seeJourneyBtn) {
        seeJourneyBtn.addEventListener('click', (e) => {
            e.preventDefault();
            alert(currentLang === 'en' ? '📖 Discover our journey of bringing light to rural India!' : '📖 ग्रामीण भारत में रोशनी लाने की हमारी यात्रा देखें!');
        });
    }
    const joinRevolutionBtn = document.getElementById('joinRevolutionBtn');
    if (joinRevolutionBtn) {
        joinRevolutionBtn.addEventListener('click', (e) => {
            e.preventDefault();
            alert(currentLang === 'en' ? '🤝 Join VIGRID movement – contact us at info@vigrid.com' : '🤝 विग्रिड आंदोलन से जुड़ें – हमसे संपर्क करें info@vigrid.com');
        });
    }

    // Footer newsletter
    const footerBtn = document.getElementById('footerNewsBtn');
    const footerEmail = document.getElementById('footerNewsEmail');
    const footerFeed = document.getElementById('footerNewsFeedback');
    if (footerBtn && footerEmail) {
        footerBtn.addEventListener('click', (e) => {
            e.preventDefault();
            const email = footerEmail.value.trim();
            if (!email || !/^[^\s@]+@([^\s@.,]+\.)+[^\s@.,]{2,}$/.test(email)) {
                footerFeed.innerHTML = '<span style="color:#ffcc80;">⚠️ ' + (currentLang === 'en' ? 'Valid email required' : 'मान्य ईमेल आवश्यक') + '</span>';
                return;
            }
            footerFeed.innerHTML = '<span style="color:#c8e6b5;">✅ ' + (currentLang === 'en' ? 'Subscribed!' : 'सदस्यता ली गई!') + '</span>';
            footerEmail.value = '';
            setTimeout(() => footerFeed.innerHTML = '', 3000);
        });
    }

    // Social icons alert
    const socialIcons = document.querySelectorAll('.copyright i, .social-contact a');
    socialIcons.forEach(icon => {
        icon.style.cursor = 'pointer';
        icon.addEventListener('click', () => {
            alert('🌍 ' + (currentLang === 'en' ? 'Connect with VIGRID on social media!' : 'सोशल मीडिया पर विग्रिड से जुड़ें!'));
        });
    });
});
